package com.goldlab.management.ui

import android.content.Context
import android.graphics.Paint
import android.graphics.pdf.PdfDocument
import android.os.Bundle
import android.os.CancellationSignal
import android.os.ParcelFileDescriptor
import android.print.PageRange
import android.print.PrintAttributes
import android.print.PrintDocumentAdapter
import android.print.PrintDocumentInfo
import android.print.PrintManager
import com.goldlab.management.data.PurchaseEntity
import java.io.ByteArrayOutputStream
import java.io.FileOutputStream
import java.math.BigDecimal
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object ReceiptPdf {
    private fun due(p: PurchaseEntity): String =
        runCatching {
            BigDecimal(p.totalAmount)
                .subtract(BigDecimal(p.paidAmount))
                .toPlainString()
        }.getOrDefault("—")

    fun create(p: PurchaseEntity): ByteArray {
        val document = PdfDocument()
        val page = document.startPage(
            PdfDocument.PageInfo.Builder(595, 842, 1).create()
        )
        val canvas = page.canvas

        val title = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            textSize = 24f
            isFakeBoldText = true
        }
        val heading = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            textSize = 15f
            isFakeBoldText = true
        }
        val body = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            textSize = 12f
        }
        val small = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            textSize = 10f
        }
        val line = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            strokeWidth = 1f
        }

        var y = 55f
        canvas.drawText("SNJ GOLD LAB", 40f, y, title)
        y += 25f
        canvas.drawText("GOLD & SILVER LABORATORY", 40f, y, body)
        y += 35f
        canvas.drawLine(40f, y, 555f, y, line)
        y += 28f

        canvas.drawText("PURCHASE RECEIPT", 40f, y, heading)
        y += 25f
        canvas.drawText("Transaction: ${p.transactionId}", 40f, y, body)
        y += 20f
        canvas.drawText(
            "Date: ${SimpleDateFormat("dd MMM yyyy, hh:mm a", Locale.getDefault()).format(Date(p.createdAt))}",
            40f, y, body
        )
        y += 32f

        canvas.drawText("PARTY DETAILS", 40f, y, heading)
        y += 22f
        canvas.drawText("Name: ${p.partyName}", 40f, y, body)
        y += 19f
        canvas.drawText("Phone: ${p.phone.ifBlank { "—" }}", 40f, y, body)
        y += 32f

        canvas.drawText("ITEM DETAILS", 40f, y, heading)
        y += 22f
        canvas.drawText("Metal: ${p.metal}", 40f, y, body)
        y += 19f
        canvas.drawText("Product: ${p.productType}", 40f, y, body)
        y += 19f
        canvas.drawText("Purity / fineness: ${p.purity}", 40f, y, body)
        y += 19f
        canvas.drawText("Weight: ${p.weight} ${p.weightUnit}", 40f, y, body)
        y += 19f
        canvas.drawText("Rate: PKR ${p.rate} ${p.rateUnit}", 40f, y, body)
        y += 32f

        canvas.drawLine(40f, y, 555f, y, line)
        y += 28f
        canvas.drawText("Total amount", 40f, y, body)
        canvas.drawText("PKR ${p.totalAmount}", 360f, y, heading)
        y += 25f
        canvas.drawText("Paid amount", 40f, y, body)
        canvas.drawText("PKR ${p.paidAmount}", 360f, y, body)
        y += 25f
        canvas.drawText("Outstanding due", 40f, y, heading)
        canvas.drawText("PKR ${due(p)}", 360f, y, heading)
        y += 35f

        if (p.notes.isNotBlank()) {
            canvas.drawText("Notes: ${p.notes.take(75)}", 40f, y, small)
            y += 22f
        }

        canvas.drawLine(40f, y, 555f, y, line)
        y += 25f
        canvas.drawText("Generated by SNJ Gold Lab", 40f, y, small)
        y += 18f
        canvas.drawText("Please keep this receipt for your records.", 40f, y, small)

        document.finishPage(page)
        val output = ByteArrayOutputStream()
        document.writeTo(output)
        document.close()
        return output.toByteArray()
    }

    fun print(context: Context, purchase: PurchaseEntity) {
        val manager = context.getSystemService(Context.PRINT_SERVICE) as PrintManager
        val pdfBytes = create(purchase)

        manager.print(
            "SNJ-${purchase.transactionId}",
            object : PrintDocumentAdapter() {
                override fun onLayout(
                    oldAttributes: PrintAttributes?,
                    newAttributes: PrintAttributes,
                    cancellationSignal: CancellationSignal,
                    callback: LayoutResultCallback,
                    extras: Bundle?
                ) {
                    if (cancellationSignal.isCanceled) {
                        callback.onLayoutCancelled()
                        return
                    }
                    val info = PrintDocumentInfo.Builder(
                        "SNJ-${purchase.transactionId}.pdf"
                    ).setContentType(PrintDocumentInfo.CONTENT_TYPE_DOCUMENT)
                        .setPageCount(1)
                        .build()
                    callback.onLayoutFinished(info, true)
                }

                override fun onWrite(
                    pages: Array<out PageRange>,
                    destination: ParcelFileDescriptor,
                    cancellationSignal: CancellationSignal,
                    callback: WriteResultCallback
                ) {
                    try {
                        if (cancellationSignal.isCanceled) {
                            callback.onWriteCancelled()
                            return
                        }
                        FileOutputStream(destination.fileDescriptor).use {
                            it.write(pdfBytes)
                            it.flush()
                        }
                        callback.onWriteFinished(arrayOf(PageRange.ALL_PAGES))
                    } catch (e: Exception) {
                        callback.onWriteFailed(e.message)
                    }
                }
            },
            PrintAttributes.Builder()
                .setMediaSize(PrintAttributes.MediaSize.ISO_A4)
                .setResolution(PrintAttributes.Resolution("snj", "SNJ", 300, 300))
                .setMinMargins(PrintAttributes.Margins.NO_MARGINS)
                .build()
        )
    }
}
